import random
board = [[" " for _ in range(3)] for _ in range(3)]
def display_board():
    print("\n")
    for row in board:
        print(" | ".join(row))
        print("-" * 9)
def check_winner(symbol):
    for row in board:
        if row[0] == row[1] == row[2] == symbol:
            return True
    for col in range(3):
        if board[0][col] == board[1][col] == board[2][col] == symbol:
            return True
    if board[0][0] == board[1][1] == board[2][2] == symbol:
        return True
    if board[0][2] == board[1][1] == board[2][0] == symbol:
        return True
    return False
def is_draw():
    for row in board:
        if " " in row:
            return False
    return True
def human_move():
    while True:
        try:
            row = int(input("Enter row (0-2): "))
            col = int(input("Enter column (0-2): "))
            if board[row][col] == " ":
                board[row][col] = "X"
                break
            else:
                print("Cell already occupied.")
        except:
            print("Invalid input. Try again.")
def computer_move():
    empty_cells = []
    for i in range(3):
        for j in range(3):
            if board[i][j] == " ":
                empty_cells.append((i, j))
    row, col = random.choice(empty_cells)
    board[row][col] = "O"
print("TIC-TAC-TOE")
print("Human = X")
print("Computer = O")
display_board()
while True:
    human_move()
    display_board()
    if check_winner("X"):
        print("Human Wins!")
        break
    if is_draw():
        print("Game Draw!")
        break
    print("Computer's Turn...")
    computer_move()
    display_board()
    if check_winner("O"):
        print("Computer Wins!")
        break
    if is_draw():
        print("Game Draw!")
        break

